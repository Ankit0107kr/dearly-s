export const productBySlug = new Map(products.map((p) => [p.slug, p]));
export const productById = new Map(products.map((p) => [p.id, p]));

export const getProduct = (slug: string) => productBySlug.get(slug);

export const relatedProducts = (product: Product, limit = 4) =>
  products
    .filter((p) => p.id !== product.id)
    .map((p) => {
      const sharedOccasions = p.occasionIds.filter((o) =>
        product.occasionIds.includes(o),
      ).length;
      const sameCategory = p.categoryId === product.categoryId ? 2 : 0;
      return { p, score: sharedOccasions + sameCategory };
    })
    .sort((a, b) => b.score - a.score)
    .slice(0, limit)
    .map((x) => x.p);
